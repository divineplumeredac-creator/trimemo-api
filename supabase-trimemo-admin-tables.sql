-- Tables requises par l'espace administrateur et les comptes clients Trimémo.
-- À exécuter une fois dans le SQL Editor du projet Supabase utilisé par trimemo-api.
-- L'API utilise exclusivement SUPABASE_SERVICE_ROLE_KEY côté serveur.

create table if not exists public.trimemo_client_projects (
  user_id uuid not null references auth.users(id) on delete cascade,
  project_id uuid not null,
  subject text not null default 'Projet académique',
  payment_status text not null default 'draft' check (payment_status in ('draft','paid')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, project_id)
);
create index if not exists trimemo_client_projects_project_id_idx
  on public.trimemo_client_projects(project_id);
create index if not exists trimemo_client_projects_updated_at_idx
  on public.trimemo_client_projects(updated_at desc);
alter table public.trimemo_client_projects enable row level security;
revoke all on public.trimemo_client_projects from anon, authenticated;

create table if not exists public.trimemo_admin_settings (
  id text primary key,
  pricing_config jsonb not null default '{}'::jsonb,
  quotas jsonb not null default '{}'::jsonb,
  usage_costs jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by text
);
alter table public.trimemo_admin_settings enable row level security;
revoke all on public.trimemo_admin_settings from anon, authenticated;

create table if not exists public.trimemo_admin_logs (
  id bigint generated by default as identity primary key,
  actor text not null default 'system',
  category text not null default 'application',
  severity text not null default 'info',
  action text not null default 'event',
  message text not null default '',
  request_path text,
  status_code integer,
  request_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists trimemo_admin_logs_created_at_idx
  on public.trimemo_admin_logs(created_at desc);
alter table public.trimemo_admin_logs enable row level security;
revoke all on public.trimemo_admin_logs from anon, authenticated;

create table if not exists public.trimemo_openai_usage (
  id bigint generated by default as identity primary key,
  endpoint text not null,
  model text not null,
  input_tokens bigint not null default 0,
  output_tokens bigint not null default 0,
  total_tokens bigint not null default 0,
  estimated_cost_usd numeric(14,6),
  status text not null default 'success' check (status in ('success','error','incomplete')),
  duration_ms bigint not null default 0,
  request_id text,
  error_code text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists trimemo_openai_usage_created_at_idx
  on public.trimemo_openai_usage(created_at desc);
create index if not exists trimemo_openai_usage_endpoint_idx
  on public.trimemo_openai_usage(endpoint, created_at desc);
alter table public.trimemo_openai_usage enable row level security;
revoke all on public.trimemo_openai_usage from anon, authenticated;

create table if not exists public.trimemo_generation_quota_usage (
  id bigint generated by default as identity primary key,
  project_id uuid not null,
  endpoint text not null,
  units integer not null default 1 check (units >= 0),
  status text not null default 'success',
  created_at timestamptz not null default now()
);
create index if not exists trimemo_generation_quota_project_endpoint_idx
  on public.trimemo_generation_quota_usage(project_id, endpoint, status);
create index if not exists trimemo_generation_quota_created_at_idx
  on public.trimemo_generation_quota_usage(created_at desc);
alter table public.trimemo_generation_quota_usage enable row level security;
revoke all on public.trimemo_generation_quota_usage from anon, authenticated;
