-- Trimémo : demandes de révision humaine et livraisons
create table if not exists public.trimemo_human_revisions (
 id bigint generated by default as identity primary key,
 user_id uuid not null, project_id uuid not null, client_email text not null,
 document_title text not null, instructions text not null,
 attachment_name text not null, attachment_type text not null default 'application/octet-stream',
 attachment_base64 text not null,
 status text not null default 'pending' check(status in ('pending','in_progress','completed')),
 admin_notes text not null default '', delivery_name text, delivery_type text, delivery_base64 text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), completed_at timestamptz
);
create index if not exists trimemo_human_revisions_status_created_idx on public.trimemo_human_revisions(status,created_at desc);
create index if not exists trimemo_human_revisions_user_created_idx on public.trimemo_human_revisions(user_id,created_at desc);
alter table public.trimemo_human_revisions enable row level security;
revoke all on public.trimemo_human_revisions from anon, authenticated;
